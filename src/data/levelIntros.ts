import type { CharacterId, StoryFlags } from './types';

export interface LevelIntro {
  character: CharacterId;
  lines: string[];
  /** Реплика-последствие прошлых решений (подсвечивается). */
  echo?: string;
}

export function getLevelIntro(level: number, s: StoryFlags): LevelIntro {
  switch (level) {
    case 1:
      return {
        character: 'boss',
        lines: [
          'Начальник: «Первый день. Двадцать объектов — и смена закрыта».',
          '«Тащи в контейнер или тапай: объект, потом контейнер. Не спеши, но и не зевай».',
        ],
      };
    case 2:
      return {
        character: 'robotKitten',
        lines: ['Начальник: «Держи Лассо. Если что-то убегает — тяни к себе»', 'Лента разгоняется.'],
        echo:
          s.sad_villain === 'rules' ? 'Контейнер «Опасное» сегодня тише обычного.'
          : s.sad_villain === 'saved' ? 'У пульта — клочок чёрной ткани и кошачья шерсть.'
          : s.sad_villain === 'used' ? 'Котёнок спит у тебя на коленях. Мурлычет, когда страшно.'
          : undefined,
      };
    case 3:
      return {
        character: 'curator',
        lines: ['Сегодня смену проверяет Куратор.', 'Начальник: «Ни одной ошибки. Слышишь? И делай, что я скажу»'],
        echo:
          s.robot_kitten === 'memory' ? 'Чип в кармане тёплый. Иногда он будто шепчет.'
          : s.robot_kitten === 'saved' ? 'Робот-котёнок у пульта поднимает уши, когда гаснет свет.'
          : s.robot_kitten === 'rules' ? 'В контейнере «Техника» что-то ещё светится.'
          : undefined,
      };
    case 4:
      return {
        character: 'whisper',
        lines: ['Лампы мигают. Между контейнерами что-то движется.'],
        echo:
          s.whisper === 'listened' ? 'Ты помнишь слова Шёпота: «Они падают в Пустоту».'
          : s.whisper === 'reported' ? 'После доноса Начальник стал добрее. А тени — злее.'
          : 'Ты так и не ответил Шёпоту. Он всё ещё ждёт.',
      };
    case 5:
      return {
        character: 'whisper',
        lines: ['Дым над лентой.', 'Сегодня на ленте будет кто-то, кто не объект. Некоторые вещи светятся фиолетовым — они из Пустоты.'],
      };
    case 6:
      return {
        character: 'boss',
        lines: ['Начальник: «Сегодня я лично слежу за сменой. Два приказа. Без обсуждений»'],
        echo:
          s.whisperSaved ? 'Шёпот рядом: «Куратор придёт. Не бойся его вопроса».'
          : s.whisper5 === 'reported' ? 'Начальник: «За Шёпота — спасибо. Куратор доволен».'
          : undefined,
      };
    case 7:
      return {
        character: 'misha',
        lines: ['Вторая лента. Начальник: «Двойная норма».', 'Туман над цехом пахнет чем-то знакомым.'],
        echo: s.hasChip ? 'Чип в кармане стучит, как маленькое сердце.' : undefined,
      };
    case 8:
      return {
        character: 'shadow',
        lines: ['На ленте — тени. Не трогай тех, у кого вместо лица «???». Каждая такая сортировка — минус жизнь.'],
        echo:
          s.ex === 'talked' ? 'После разговора с Ней легче. Будто можно и не выбирать.'
          : s.misha === 'chip' || s.misha === 'gift' ? 'Где-то за лентой смеётся Миша.'
          : undefined,
      };
    case 9:
      return {
        character: 'whisper',
        lines: ['Лента уходит вниз, в темноту.', 'Свет здесь дают только правильные ответы.'],
        echo: s.whisperSaved ? 'Шёпот светит рядом: «Я знаю дорогу».' : 'Здесь темно. И никто не подскажет.',
      };
    default:
      return {
        character: 'curator',
        lines: [
          'Три ленты. На них не вещи — то, что ты чувствовал.',
          'И вопросы. Их нельзя взять без Сомнения. Пропускать вопросы — не ошибка.',
          'Куратор ждёт в конце смены.',
        ],
        echo: s.shadow === 'freed' ? 'Сомнение в руке: вопросы теперь можно взять.' : undefined,
      };
  }
}
