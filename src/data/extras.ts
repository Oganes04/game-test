export function award(s: Save): Partial<Save> {
  const earned = achievements
    .filter(([id, , test]) => !s.achievements.includes(id) && test(s))
    .map(([id]) => id)
  return earned.length
    ? {
        coins: s.coins + earned.length * 15,
        achievements: [...s.achievements, ...earned],
      }
    : {}
}
